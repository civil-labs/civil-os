// Writes sdk/js/index.js and index.d.ts: one `export *` per generated public
// API module under gen/civil/public. Never edit or commit those files; this
// script runs from `mise run generate` and as the npm `prepack` script, so a
// new public proto is exported with no manual step.
//
// Generated dependencies (google, buf/validate, gnostic) stay importable by
// the generated code but are not re-exported, as in the old civil-api-js.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(pkgDir, "gen", "civil", "public");

function walk(dir) {
  let out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out = out.concat(walk(path));
    else if (name.endsWith("_pb.js")) out.push(path);
  }
  return out;
}

let modules;
try {
  modules = walk(publicDir)
    .map((p) => "./" + relative(pkgDir, p).split(sep).join("/"))
    .sort();
} catch (err) {
  console.error(`gen-index: cannot read ${publicDir}; run \`mise run generate\` first (${err.message})`);
  process.exit(1);
}
if (modules.length === 0) {
  console.error(`gen-index: no *_pb.js files under ${publicDir}; run \`mise run generate\` first`);
  process.exit(1);
}

const header = "// Generated by sdk/js/scripts/gen-index.mjs. Do not edit.\n";
const body = modules.map((m) => `export * from "${m}";`).join("\n") + "\n";
writeFileSync(join(pkgDir, "index.js"), header + body);
writeFileSync(join(pkgDir, "index.d.ts"), header + body);
console.log(`gen-index: ${modules.length} modules exported`);
